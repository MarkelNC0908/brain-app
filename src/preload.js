const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('brain', {
  platform: process.platform,
  profState: () => ipcRenderer.invoke('prof:state'),
  profLogin: (id, pin) => ipcRenderer.invoke('prof:login', id, pin),
  profCreate: (d) => ipcRenderer.invoke('prof:create', d),
  profUpdate: (id, d, pin) => ipcRenderer.invoke('prof:update', id, d, pin),
  profDelete: (id, pin) => ipcRenderer.invoke('prof:delete', id, pin),
  profLogout: () => ipcRenderer.invoke('prof:logout'),
  profPickFolder: () => ipcRenderer.invoke('prof:pickFolder'),
  profInitBrain: (p) => ipcRenderer.invoke('prof:initBrain', p),
  subjects: () => ipcRenderer.invoke('subjects'),
  subjAdd: (s, n) => ipcRenderer.invoke('subj:add', s, n),
  onEditProfile: (cb) => ipcRenderer.on('ui:editprofile', cb),
  index: () => ipcRenderer.invoke('vault:index'),
  pick: () => ipcRenderer.invoke('vault:pick'),
  external: (u) => ipcRenderer.invoke('open:external', u),
  onChanged: (cb) => ipcRenderer.on('vault:changed', cb),
  pushPreview: () => ipcRenderer.invoke('push:preview'),
  pushDo: (msg) => ipcRenderer.invoke('push:do', msg),
  onPushRequest: (cb) => ipcRenderer.on('push:request', cb),
  termStart: (c, r) => ipcRenderer.invoke('term:start', c, r),
  termWrite: (d) => ipcRenderer.send('term:write', d),
  termResize: (c, r) => ipcRenderer.send('term:resize', c, r),
  termKill: () => ipcRenderer.invoke('term:kill'),
  onTermData: (cb) => ipcRenderer.on('term:data', (_e, d) => cb(d)),
  onTermExit: (cb) => ipcRenderer.on('term:exit', cb),
  onTermToggle: (cb) => ipcRenderer.on('ui:term', cb),
  dashMove: (card, col, nota) => ipcRenderer.invoke('dash:move', card, col, nota),
  bbiScan: () => ipcRenderer.invoke('bbi:scan'),
  bbiCancel: () => ipcRenderer.invoke('bbi:cancel'),
  onBBIProgress: (cb) => ipcRenderer.on('bbi:progress', (_e, p) => cb(p)),
  bbiApply: (f, c, d) => ipcRenderer.invoke('bbi:apply', f, c, d),
  bbState: () => ipcRenderer.invoke('bb:state'),
  bbCheck: () => ipcRenderer.invoke('bb:check'),
  bbLogin: () => ipcRenderer.invoke('bb:login'),
  bbSeen: () => ipcRenderer.invoke('bb:seen'),
  onBBChanged: (cb) => ipcRenderer.on('bb:changed', cb),
  onAvisos: (cb) => ipcRenderer.on('ui:avisos', cb),
  openFile: (rel) => ipcRenderer.invoke('file:open', rel),
  dashAdd: (d) => ipcRenderer.invoke('dash:add', d),
  dashData: () => ipcRenderer.invoke('dash:data'),
  horarioData: () => ipcRenderer.invoke('horario:data'),
  status: () => ipcRenderer.invoke('git:status'),
  sync: () => ipcRenderer.invoke('git:sync'),
  uploadInfo: () => ipcRenderer.invoke('upload:info'),
  pickFiles: () => ipcRenderer.invoke('upload:pick'),
  copyFiles: (sigla, sub, paths) => ipcRenderer.invoke('upload:copy', sigla, sub, paths),
  pathOf: (f) => webUtils.getPathForFile(f),   // ruta real de un archivo arrastrado
  onSyncStart: (cb) => ipcRenderer.on('sync:start', cb),
  onSyncDone: (cb) => ipcRenderer.on('sync:done', (_e, r) => cb(r)),
  onSyncRequest: (cb) => ipcRenderer.on('sync:request', cb),
  onSearch: (cb) => ipcRenderer.on('ui:search', cb),
});
